/* BriefDrop – first-time Home. "Gimme a brief" asks BriefAI (Claude via your backend, or a local remix) for a fresh brief every time. */
(() => {
  'use strict';

  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => Array.from(r.querySelectorAll(s));
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  const finePointer = matchMedia('(hover: hover) and (pointer: fine)').matches;
  const IC = window.ICONS || {};
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  const toast = $('#toast');
  let toastTimer = 0;
  const say = (msg) => { toast.textContent = msg; toast.classList.add('is-on'); clearTimeout(toastTimer); toastTimer = setTimeout(() => toast.classList.remove('is-on'), 2800); };

  /* intro: headline words rise */
  const title = $('.empty__title');
  if (title && !reduce) {
    const text = title.textContent.trim();
    title.setAttribute('aria-label', text); title.textContent = '';
    text.split(/\s+/).forEach((w, i, a) => {
      const s = document.createElement('span'); s.className = 'w'; s.setAttribute('aria-hidden', 'true'); s.style.setProperty('--i', i); s.textContent = w;
      title.append(s); if (i < a.length - 1) title.append(' ');
    });
  }

  /* illustration: pointer parallax + click to scatter question marks */
  const art = $('#art'), img = $('.empty__img', art);
  if (finePointer && !reduce) {
    let frame = 0;
    addEventListener('pointermove', (e) => {
      if (frame) return;
      frame = requestAnimationFrame(() => { frame = 0; art.style.setProperty('--px', ((e.clientX / innerWidth) - .5).toFixed(3)); art.style.setProperty('--py', ((e.clientY / innerHeight) - .5).toFixed(3)); });
    }, { passive: true });
  }
  const glyphs = ['?', '?', '!', '✦'];
  const colors = ['#f9e8c3', '#faae1f', '#7aa5ff', '#ffffff'];
  function scatter(x, y, n = 9) {
    if (reduce) return;
    for (let i = 0; i < n; i++) {
      const g = document.createElement('span'); g.className = 'glyph'; g.textContent = glyphs[i % glyphs.length];
      g.style.cssText = `left:${x}px;top:${y}px;font-size:${14 + Math.random() * 16}px;color:${colors[i % colors.length]}`;
      document.body.append(g);
      const a = -Math.PI / 2 + (Math.random() - .5) * 2.4, d = 60 + Math.random() * 110;
      g.animate([{ transform: 'translate(-50%,-50%) scale(.4) rotate(0)', opacity: 0 }, { transform: `translate(calc(-50% + ${Math.cos(a) * d}px), calc(-50% + ${Math.sin(a) * d}px)) scale(1) rotate(${Math.random() * 60 - 30}deg)`, opacity: 1, offset: .35 }, { transform: `translate(calc(-50% + ${Math.cos(a) * d * 1.2}px), calc(-50% + ${Math.sin(a) * d + 70}px)) scale(.7) rotate(${Math.random() * 120 - 60}deg)`, opacity: 0 }], { duration: 1000 + Math.random() * 500, easing: 'cubic-bezier(.2,.7,.4,1)' }).onfinish = () => g.remove();
    }
  }
  art.addEventListener('click', (e) => {
    scatter(e.clientX, e.clientY);
    if (!reduce) img.animate([{ transform: 'rotate(0) scale(1)' }, { transform: 'rotate(-1.8deg) scale(1.03)', offset: .3 }, { transform: 'rotate(1.3deg) scale(1.015)', offset: .6 }, { transform: 'rotate(0) scale(1)' }], { duration: 600, easing: 'cubic-bezier(.3,1.2,.5,1)' });
  });

  /* brief sheet */
  const dlg = $('#detail');
  let current = null, busy = false;
  const metaHTML = (b) => `<span>${esc(b.domain)}</span><i></i><span>${esc(b.level)}</span><i></i><span>${esc(b.time)}</span>`;

  function fill(b, animate) {
    current = b;
    $('#d-title').textContent = b.title;
    $('#d-meta').innerHTML = metaHTML(b);
    const src = $('#d-src');
    src.className = 'src' + (b.source === 'claude' ? ' src--claude' : '');
    src.textContent = b.source === 'claude' ? '✦ Claude' : 'Offline mix';
    src.title = b.source === 'claude' ? 'Generated by Claude' : 'Claude couldn’t be reached, so this was remixed on your device';
    const list = $('#d-list'); list.replaceChildren();
    (b.deliverables || []).forEach((d, i) => {
      const li = document.createElement('li');
      li.innerHTML = `<label><input type="checkbox" data-i="${i}"><span class="box" aria-hidden="true">${IC.check || ''}</span><span class="txt-l">${esc(d)}</span></label>`;
      list.append(li);
    });
    prog();
    if (animate && !reduce) {
      [$('.sheet__top', dlg), $('#d-title'), $('#d-meta'), ...$$('#d-list li')].forEach((el, n) => el.animate([{ opacity: 0, transform: 'translateY(12px)' }, { opacity: 1, transform: 'none' }], { duration: 420, delay: 60 + n * 60, easing: 'cubic-bezier(.2,.8,.2,1)', fill: 'backwards' }));
    }
  }
  function prog() {
    const boxes = $$('#d-list input'); const n = boxes.filter((x) => x.checked).length;
    $('#d-prog').textContent = boxes.length ? (n === boxes.length ? 'All done. Nice work.' : `${n} of ${boxes.length} done`) : '';
  }
  $('#d-list').addEventListener('change', prog);

  async function make() {
    const t0 = performance.now();
    const avoid = current ? [current.title] : [];
    const { briefs } = await window.BriefAI.generate({ count: 1, avoid });
    const wait = 800 - (performance.now() - t0);
    if (wait > 0 && !reduce) await new Promise((r) => setTimeout(r, wait));
    return briefs[0];
  }

  const gimme = $('#gimme'), label = $('.cta__label', gimme);
  gimme.addEventListener('click', async () => {
    if (busy) return;
    busy = true; gimme.disabled = true; gimme.classList.add('is-loading'); label.textContent = 'Finding one';
    art.classList.add('is-thinking');
    try {
      const b = await make();
      fill(b, false);
      if (typeof dlg.showModal === 'function') dlg.showModal();
    } finally {
      art.classList.remove('is-thinking'); gimme.disabled = false; gimme.classList.remove('is-loading'); label.textContent = 'Gimme a brief'; busy = false;
    }
  });

  const again = $('#d-again'), againLabel = $('span', again);
  again.addEventListener('click', async () => {
    if (busy) return;
    busy = true; again.disabled = true; againLabel.textContent = 'Thinking…';
    const dice = $('.ic', again);
    if (!reduce) dice.animate([{ transform: 'rotate(0)' }, { transform: 'rotate(540deg) scale(1.25)', offset: .6 }, { transform: 'rotate(720deg)' }], { duration: 700, easing: 'cubic-bezier(.2,.8,.2,1)' });
    try { fill(await make(), true); }
    finally { again.disabled = false; againLabel.textContent = 'Another one'; busy = false; }
  });

  /* Begin: carry this brief into the full Home */
  $('#d-begin').addEventListener('click', () => {
    if (!current) return;
    try { sessionStorage.setItem('briefdrop.first', JSON.stringify(current)); localStorage.setItem('briefdrop.onboarded', '1'); } catch (_) {}
    say('Let’s go.');
    setTimeout(() => { location.href = 'home.html'; }, reduce ? 0 : 450);
  });

  document.addEventListener('click', (e) => {
    const cl = e.target.closest('[data-close]'); if (cl) { cl.closest('dialog').close(); return; }
    if (e.target instanceof HTMLDialogElement) e.target.close();
  });

  /* header + nav */
  const bell = $('#bell');
  bell.addEventListener('click', () => { bell.classList.remove('ring'); void bell.offsetWidth; bell.classList.add('ring'); say('No notifications yet.'); });
  $$('[data-soon]').forEach((t) => t.addEventListener('click', () => { t.classList.remove('bump'); void t.offsetWidth; t.classList.add('bump'); say(`${t.dataset.soon} isn’t built in this prototype yet.`); }));
  if (finePointer && !reduce) {
    gimme.addEventListener('pointermove', (e) => { const r = gimme.getBoundingClientRect(); gimme.style.translate = `${((e.clientX - (r.left + r.width / 2)) * 0.06).toFixed(1)}px ${((e.clientY - (r.top + r.height / 2)) * 0.2).toFixed(1)}px`; });
    gimme.addEventListener('pointerleave', () => { gimme.style.translate = ''; });
  }
})();
