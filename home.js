/* BriefDrop – Home interactions. Briefs come from BriefAI (Claude via your backend, or a local remix). */
(() => {
  'use strict';

  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => Array.from(r.querySelectorAll(s));
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  const finePointer = matchMedia('(hover: hover) and (pointer: fine)').matches;
  const IC = window.ICONS || {};
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const store = {
    get(k, d) { try { const v = localStorage.getItem(k); return v == null ? d : JSON.parse(v); } catch (_) { return d; } },
    set(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (_) {} },
  };

  const hero = $('#hero'), dailyEl = $('#daily'), seeAll = $('#seeall');
  const toast = $('#toast');
  let toastTimer = 0;
  const say = (msg) => { toast.textContent = msg; toast.classList.add('is-on'); clearTimeout(toastTimer); toastTimer = setTimeout(() => toast.classList.remove('is-on'), 2800); };

  /* ── state ─────────────────────────────────────────────────────────── */
  let saved = store.get('briefdrop.saved', []); if (!Array.isArray(saved)) saved = [];
  const started = new Set();
  const S = { hero: null, daily: [], more: [], expanded: false, busy: false };
  const all = () => [S.hero, ...S.daily, ...S.more, ...saved].filter(Boolean);
  const find = (id) => all().find((b) => b.id === id);
  const isSaved = (b) => saved.some((s) => s.id === b.id || s.title === b.title);

  /* ── rendering ─────────────────────────────────────────────────────── */
  const metaHTML = (b) => `<div class="meta"><span>${esc(b.domain)}</span><i></i><span>${esc(b.level)}</span><i></i><span>${esc(b.time)}</span></div>`;
  const bmHTML = (b) => `<button class="bm" type="button" data-bm="${esc(b.id)}" aria-pressed="${isSaved(b)}" aria-label="${isSaved(b) ? 'Remove from saved' : 'Save brief'}">${IC.bookmark || ''}</button>`;
  const kick = (t, b) => `${esc(t)}${started.has(b.id) ? ' · IN PROGRESS' : ''}`;
  const srcHTML = (b) => b.source === 'claude'
    ? `<span class="src src--claude" title="Generated by Claude">✦ Claude</span>`
    : `<span class="src" title="Claude couldn’t be reached, so this was remixed on your device">Offline mix</span>`;

  const heroHTML = (b) => `${bmHTML(b)}
    <div class="card__top"><p class="kick">${kick('YOUR NEXT BEST BRIEF', b)}</p>${srcHTML(b)}</div>
    <h2 class="card__title" data-title>${esc(b.title)}</h2>
    ${metaHTML(b)}
    <div class="card__act"><button class="cta cta--card" type="button" data-start="${esc(b.id)}">Start this one</button></div>`;
  const dailyHTML = (b) => `${bmHTML(b)}
    <div class="card__top"><p class="kick">${kick('DAILY', b)}</p></div>
    <h3 class="card__title" data-title>${esc(b.title)}</h3>
    <div class="card__foot">${metaHTML(b)}<button class="cta cta--sm" type="button" data-start="${esc(b.id)}">Start</button></div>`;
  const skeleton = (withBtn) => `<div class="sk sk--k"></div><div class="sk sk--t"></div><div class="sk sk--t sk--s"></div><div class="sk sk--m"></div>${withBtn ? '<div class="sk sk--b"></div>' : ''}<p class="thinking"><i></i><i></i><i></i><span>Thinking up a brief…</span></p>`;

  function splitTitle(el) {
    if (!el || reduce) return;
    const text = el.textContent;
    el.setAttribute('aria-label', text);
    el.textContent = '';
    text.split(/\s+/).forEach((w, i, a) => {
      const s = document.createElement('span');
      s.className = 'w'; s.setAttribute('aria-hidden', 'true'); s.style.setProperty('--i', i); s.textContent = w;
      el.append(s); if (i < a.length - 1) el.append(' ');
    });
  }

  function paintHero() {
    hero.innerHTML = heroHTML(S.hero); hero.dataset.id = S.hero.id; splitTitle($('[data-title]', hero));
  }
  function cardEl(b, i) {
    const a = document.createElement('article');
    a.className = 'card'; a.dataset.id = b.id; a.style.setProperty('--i', i);
    a.innerHTML = dailyHTML(b); splitTitle($('[data-title]', a)); return a;
  }
  function paintDaily() {
    const items = [...S.daily, ...S.more];
    dailyEl.replaceChildren(...items.map((b, i) => cardEl(b, i)));
    dailyEl.classList.toggle('is-short', !S.expanded);
  }
  function paintSkeleton(el, withBtn) { el.innerHTML = skeleton(withBtn); }
  const repaintMarks = () => {
    $$('[data-bm]').forEach((btn) => { const b = find(btn.dataset.bm); if (!b) return; const on = isSaved(b); btn.setAttribute('aria-pressed', String(on)); btn.setAttribute('aria-label', on ? 'Remove from saved' : 'Save brief'); });
    const n = $('#saved-n'); n.hidden = saved.length === 0; n.textContent = saved.length;
  };

  /* ── generating ────────────────────────────────────────────────────── */
  async function make(opts) {
    const t0 = performance.now();
    const avoid = all().map((b) => b.title);
    const res = await window.BriefAI.generate({ ...opts, avoid });
    const wait = 650 - (performance.now() - t0);      // never flash: let the "thinking" state be seen
    if (wait > 0 && !reduce) await new Promise((r) => setTimeout(r, wait));
    return res;
  }

  async function boot() {
    paintSkeleton(hero, true);
    $$('.card', dailyEl).forEach((c) => paintSkeleton(c, false));
    S.busy = true;
    let first = null;
    try { first = JSON.parse(sessionStorage.getItem('briefdrop.first') || 'null'); sessionStorage.removeItem('briefdrop.first'); } catch (_) {}
    if (first && typeof first.title === 'string' && first.id) {
      // the brief they just began on the first-time screen leads the list
      const { briefs } = await make({ count: 2 });
      started.add(first.id);
      S.hero = first; S.daily = [briefs[0], briefs[1]];
    } else {
      const { briefs } = await make({ count: 3 });
      S.hero = briefs[0]; S.daily = [briefs[1], briefs[2]];
    }
    paintHero(); paintDaily(); repaintMarks(); S.busy = false;
  }

  async function swapHero(opts, { openAfter = false } = {}) {
    if (S.busy) return null;
    S.busy = true;
    hero.classList.add('is-swapping');
    paintSkeleton(hero, true);
    try {
      const { briefs } = await make({ count: 1, ...opts });
      S.hero = briefs[0];
    } finally { S.busy = false; }
    paintHero(); repaintMarks();
    if (!reduce && hero.animate) hero.animate([{ transform: 'scale(.97) rotate(-.6deg)' }, { transform: 'scale(1) rotate(0)' }], { duration: 450, easing: 'cubic-bezier(.3,1.5,.5,1)' });
    if (openAfter) openDetail(S.hero);
    return S.hero;
  }

  const inView = (el) => { const r = el.getBoundingClientRect(); return r.top >= 70 && r.bottom <= innerHeight; };
  const toHero = () => { if (!inView(hero)) hero.scrollIntoView({ behavior: reduce ? 'auto' : 'smooth', block: 'start' }); };

  /* ── detail sheet ──────────────────────────────────────────────────── */
  const dlgD = $('#detail');
  let current = null;
  function openDetail(b) {
    current = b;
    $('#d-kick').textContent = started.has(b.id) ? 'IN PROGRESS' : (b === S.hero ? 'YOUR NEXT BEST BRIEF' : 'BRIEF');
    $('#d-title').textContent = b.title;
    $('#d-meta').innerHTML = metaHTML(b).replace(/^<div class="meta">|<\/div>$/g, '');
    const list = $('#d-list'); list.replaceChildren();
    (b.deliverables || []).forEach((d, i) => {
      const li = document.createElement('li');
      li.innerHTML = `<label><input type="checkbox" data-i="${i}"><span class="box" aria-hidden="true">${IC.check || ''}</span><span class="txt-l">${esc(d)}</span></label>`;
      list.append(li);
    });
    $('#d-begin').textContent = started.has(b.id) ? 'Keep going' : 'Begin';
    syncSave(); prog();
    if (typeof dlgD.showModal === 'function') { if (!dlgD.open) dlgD.showModal(); }
  }
  function prog() {
    const boxes = $$('#d-list input'); const n = boxes.filter((x) => x.checked).length;
    $('#d-prog').textContent = boxes.length ? (n === boxes.length ? 'All done. Nice work.' : `${n} of ${boxes.length} done`) : '';
  }
  function syncSave() {
    const on = current && isSaved(current);
    const btn = $('#d-save'); btn.setAttribute('aria-pressed', String(Boolean(on))); $('span', btn).textContent = on ? 'Saved' : 'Save';
  }
  $('#d-list').addEventListener('change', prog);
  $('#d-begin').addEventListener('click', () => {
    if (!current) return;
    started.add(current.id); dlgD.close(); say('Brief started. Good luck.');
    $$(`[data-id="${CSS.escape(current.id)}"] .kick`).forEach((k) => { if (!k.textContent.includes('IN PROGRESS')) k.textContent += ' · IN PROGRESS'; });
  });
  $('#d-save').addEventListener('click', () => { if (current) toggleSave(current); syncSave(); });

  function toggleSave(b) {
    const i = saved.findIndex((s) => s.id === b.id || s.title === b.title);
    if (i >= 0) { saved.splice(i, 1); say('Removed from saved.'); } else { saved.unshift(b); say('Saved.'); }
    store.set('briefdrop.saved', saved);
    repaintMarks(); paintSavedList();
    $$(`[data-bm="${CSS.escape(b.id)}"]`).forEach((btn) => { btn.classList.remove('pop'); void btn.offsetWidth; btn.classList.add('pop'); });
  }

  /* ── saved sheet ───────────────────────────────────────────────────── */
  const dlgS = $('#savedlg');
  function paintSavedList() {
    const ul = $('#s-list'); ul.replaceChildren();
    saved.forEach((b) => {
      const li = document.createElement('li');
      li.innerHTML = `<button class="row" type="button" data-open="${esc(b.id)}"><b>${esc(b.title)}</b>${metaHTML(b)}</button><button class="rm" type="button" data-rm="${esc(b.id)}" aria-label="Remove from saved">${IC.x || ''}</button>`;
      ul.append(li);
    });
  }
  $('#saved').addEventListener('click', () => { paintSavedList(); dlgS.showModal(); });
  $('#s-list').addEventListener('click', (e) => {
    const rm = e.target.closest('[data-rm]'), op = e.target.closest('[data-open]');
    if (rm) { const b = saved.find((s) => s.id === rm.dataset.rm); if (b) toggleSave(b); }
    else if (op) { const b = saved.find((s) => s.id === op.dataset.open); if (b) { dlgS.close(); openDetail(b); } }
  });

  /* ── build my own ──────────────────────────────────────────────────── */
  const dlgB = $('#builddlg');
  const pickState = { craft: '', level: '' };
  function radios(container, items, key) {
    container.replaceChildren();
    items.forEach((t) => {
      const b = document.createElement('button'); b.type = 'button'; b.setAttribute('role', 'radio'); b.setAttribute('aria-checked', 'false'); b.textContent = t;
      b.addEventListener('click', () => {
        pickState[key] = pickState[key] === t ? '' : t;          // tap again to clear
        $$('button', container).forEach((x) => x.setAttribute('aria-checked', String(x.textContent === pickState[key])));
      });
      container.append(b);
    });
  }
  radios($('#b-craft'), window.BriefAI.DISCIPLINES, 'craft');
  radios($('#b-level'), window.BriefAI.LEVELS, 'level');
  $('#build').addEventListener('click', () => dlgB.showModal());
  $('#b-form').addEventListener('submit', async (e) => {
    e.preventDefault();
    if (S.busy) return;
    const opts = { discipline: pickState.craft, level: pickState.level, topic: $('#b-topic').value };
    dlgB.close(); toHero();
    await swapHero(opts);
  });

  /* ── global clicks ─────────────────────────────────────────────────── */
  document.addEventListener('click', (e) => {
    const st = e.target.closest('[data-start]');
    if (st) { const b = st.dataset.start ? find(st.dataset.start) : null; if (b) openDetail(b); return; }
    const bm = e.target.closest('[data-bm]');
    if (bm) { const b = find(bm.dataset.bm); if (b) toggleSave(b); return; }
    const cl = e.target.closest('[data-close]');
    if (cl) { cl.closest('dialog').close(); return; }
    if (e.target instanceof HTMLDialogElement) e.target.close();       // backdrop
  });

  /* surprise me + show me a brief */
  const surprise = $('#surprise');
  surprise.addEventListener('click', async () => {
    if (S.busy) return;
    surprise.classList.remove('spin'); void surprise.offsetWidth; surprise.classList.add('spin');
    toHero(); await swapHero({});
  });
  const show = $('#show'), showLabel = $('.cta__label', show);
  show.addEventListener('click', async () => {
    if (S.busy) return;
    show.disabled = true; show.classList.add('is-loading'); showLabel.textContent = 'Finding one';
    try { await swapHero({}, { openAfter: true }); }
    finally { show.disabled = false; show.classList.remove('is-loading'); showLabel.textContent = 'Show me a brief'; }
  });

  /* see all: reveal more daily drops (made on demand) */
  seeAll.addEventListener('click', async () => {
    if (S.busy) return;
    if (!S.expanded) {
      S.expanded = true; seeAll.setAttribute('aria-expanded', 'true'); seeAll.textContent = 'Show less';
      if (!S.more.length) {
        S.busy = true;
        for (let i = 0; i < 3; i++) { const c = document.createElement('article'); c.className = 'card'; c.innerHTML = skeleton(false); dailyEl.append(c); }
        dailyEl.classList.remove('is-short');
        const { briefs } = await make({ count: 3 });
        S.more = briefs; S.busy = false;
      }
      paintDaily();
    } else {
      S.expanded = false; seeAll.setAttribute('aria-expanded', 'false'); seeAll.textContent = 'See all';
      dailyEl.classList.add('is-short'); hero.scrollIntoView({ behavior: reduce ? 'auto' : 'smooth', block: 'start' });
    }
  });

  /* ── header + nav ──────────────────────────────────────────────────── */
  const bell = $('#bell');
  bell.addEventListener('click', () => {
    bell.classList.remove('ring'); void bell.offsetWidth; bell.classList.add('ring');
    const was = bell.classList.contains('is-read');
    bell.classList.add('is-read'); bell.setAttribute('aria-label', 'Notifications');
    say(was ? 'You’re all caught up.' : 'New brief drops are ready for you.');
  });
  const streak = $('#streak');
  streak.addEventListener('click', () => { streak.classList.remove('hot'); void streak.offsetWidth; streak.classList.add('hot'); say('4-day streak. Start a brief today to keep it going.'); });
  $$('[data-soon]').forEach((t) => t.addEventListener('click', () => {
    t.classList.remove('bump'); void t.offsetWidth; t.classList.add('bump');
    say(`${t.dataset.soon} isn’t built in this prototype yet.`);
  }));

  const bar = $('#bar');
  let ticking = false;
  addEventListener('scroll', () => { if (ticking) return; ticking = true; requestAnimationFrame(() => { ticking = false; bar.classList.toggle('is-stuck', scrollY > 8); }); }, { passive: true });

  if (finePointer && !reduce) {
    document.addEventListener('pointermove', (e) => {
      const c = e.target.closest && e.target.closest('.card'); if (!c) return;
      const r = c.getBoundingClientRect(); c.style.setProperty('--mx', (e.clientX - r.left) + 'px'); c.style.setProperty('--my', (e.clientY - r.top) + 'px');
    }, { passive: true });
    [show].forEach((b) => {
      b.addEventListener('pointermove', (e) => { const r = b.getBoundingClientRect(); b.style.translate = `${((e.clientX - (r.left + r.width / 2)) * 0.06).toFixed(1)}px ${((e.clientY - (r.top + r.height / 2)) * 0.2).toFixed(1)}px`; });
      b.addEventListener('pointerleave', () => { b.style.translate = ''; });
    });
  }

  /* intro stagger indices */
  [$('.bar__in'), hero, $('.daily__head'), ...$$('.card', dailyEl), ...$$('.tile'), show].forEach((el, i) => el && el.style.setProperty('--i', i));

  repaintMarks();
  boot();
})();
